// Builds the snippets pasted into the Webflow "LLM Rankings" page from the files in this repo.
// Usage:  node webflow/build.js
//
//   head.html             Page settings > Custom code > Inside <head>   (theme before first paint)
//   1-styles.html         Code embed 1, after the hero                  (page CSS + theme overrides)
//   2a-chart.html         Code embed 2a, after embed 1                  (chart)
//   2b-explore.html       Code embed inside the native Explore section  (model selector)
//   2c-results.html       Code embed inside the native Leaderboard section (results table)
//   3-config.html         Code embed 3                                  (loads js/bare-config.js from the latest GitHub release)
//   4-app.html            Code embed 4                                  (renders the page)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const read = f => fs.readFileSync(path.join(root, f), "utf8").trim();
const LIMIT = 50000; // Webflow's character limit per code embed / custom code field

const html = read("bare-benchmark.html");
const embeds = {};
for (const [, name, body] of html.matchAll(/<!-- WEBFLOW EMBED START: (\S+) -->([\s\S]*?)<!-- WEBFLOW EMBED END -->/g)) embeds[name] = body.trim();
for (const name of ["2a-chart", "2b-explore", "2c-results"]) if (!embeds[name]) throw new Error(`WEBFLOW EMBED block ${name} not found in bare-benchmark.html`);

const note = what => `<!-- ${what}. Generated by webflow/build.js; edit the source files, not this. -->`;
const out = {
  "head.html": `${note("BARE theme: light by default, dark when chosen")}\n<script>\n${read("js/theme.js")}\n</script>`,
  "1-styles.html": `${note("BARE styles")}\n<style>\n${read("css/bare-benchmark.css")}\n\n${read("css/theme.css")}\n</style>`,
  "2a-chart.html": `${note("BARE chart")}\n${embeds["2a-chart"]}`,
  "2b-explore.html": `${note("BARE model selector")}\n${embeds["2b-explore"]}`,
  "2c-results.html": `${note("BARE results table")}\n${embeds["2c-results"]}`,
  "3-config.html": `${note("BARE config, served from the latest GitHub release")}\n<script src="https://cdn.jsdelivr.net/gh/First-Class-Design/blueoptima-bare-benchmark@latest/js/bare-config.js"></script>`,
  "4-app.html": `${note("BARE app")}\n<script>\n${read("js/bare-benchmark.js")}\n</script>`,
};

for (const [name, text] of Object.entries(out)) {
  fs.writeFileSync(path.join(__dirname, name), text + "\n");
  const flag = text.length > LIMIT ? `  OVER the ${LIMIT} limit` : "";
  console.log(`${name.padEnd(16)} ${String(text.length).padStart(6)} chars${flag}`);
}
